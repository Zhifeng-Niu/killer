/**
 * 内置工具 — learn（创建新工具）
 *
 * Agent 通过此工具在运行时创建新能力。
 */
export class LearnTool implements Tool {
  name = 'learn';
  description = 'Create a new tool at runtime. Params: { name: string, description: string, code: string }. The code must export default { name, description, async execute(params) { ... } }. The tool will be written, loaded, and registered immediately.';

  private readonly forge: ToolForge;

  constructor(forge: ToolForge) {
    this.forge = forge;
  }

  async execute(params: unknown): Promise<ToolResult> {
    if (typeof params !== 'object' || params === null) {
      return { success: false, error: 'Invalid params. Required: { name, description, code }' };
    }

    const { name, description, code } = params as {
      name?: string;
      description?: string;
      code?: string;
    };

    if (!name) return { success: false, error: 'Tool name is required' };
    if (!description) return { success: false, error: 'Tool description is required' };
    if (!code) return { success: false, error: 'Tool code is required' };

    const result = await this.forge.create(name, description, code);

    if (result.success) {
      return {
        success: true,
        data: {
          message: `Tool "${name}" created and loaded successfully. It is now available for use.`,
          ...result.data,
        },
      };
    }

    return {
      success: false,
      error: result.error,
    };
  }
}

/**
 * 内置工具 — unlearn（移除动态工具）
 */
export class UnlearnTool implements Tool {
  name = 'unlearn';
  description = 'Remove a dynamically created tool. Params: { name: string }. Unloads the tool and deletes its file.';

  private readonly forge: ToolForge;

  constructor(forge: ToolForge) {
    this.forge = forge;
  }

  async execute(params: unknown): Promise<ToolResult> {
    if (typeof params !== 'object' || params === null) {
      return { success: false, error: 'Invalid params. Required: { name }' };
    }

    const { name } = params as { name?: string };
    if (!name) return { success: false, error: 'Tool name is required' };

    const result = await this.forge.remove(name);

    if (result.success) {
      return {
        success: true,
        data: {
          message: `Tool "${name}" removed successfully.`,
          ...result.data,
        },
      };
    }

    return { success: false, error: result.error };
  }
}

/**
 * 内置工具 — inspect_tools（检查可用工具）
 */
export class InspectToolsTool implements Tool {
  name = 'inspect_tools';
  description = 'List all available tools with descriptions and status. Use this to understand your current capabilities and identify gaps. No params needed.';
  isReadOnly = () => true;

  private readonly forge: ToolForge;

  constructor(forge: ToolForge) {
    this.forge = forge;
  }

  async execute(_params: unknown): Promise<ToolResult> {
    const tools = this.forge.inspect();
    const dynamic = tools.filter(t => t.dynamic);
    const builtin = tools.filter(t => !t.dynamic);

    return {
      success: true,
      data: {
        total: tools.length,
        builtin: builtin.length,
        dynamic: dynamic.length,
        tools: tools.map(t => ({
          name: t.name,
          description: t.description,
          type: t.dynamic ? 'dynamic' : 'builtin',
        })),
      },
    };
  }
}

/**
 * 内置工具 — self_reflect（自我内省）
 *
 * 让 Agent 看到自己的运行时状态、源码位置和能力边界。
 * 这是"照镜子"——知道自己在哪、有什么、能改什么。
 */
export class SelfReflectTool implements Tool {
  name = 'self_reflect';
  description = 'Deep introspection of your own runtime state, source code locations, and capability boundaries. Returns: runtime state, tool inventory, source paths, memory stats. Params: { aspect?: "runtime"|"tools"|"source"|"all" (default "all") }';
  isReadOnly = () => true;

  private readonly forge: ToolForge;

  constructor(forge: ToolForge) {
    this.forge = forge;
  }

  async execute(params: unknown): Promise<ToolResult> {
    const { aspect = 'all' } = (typeof params === 'object' && params !== null ? params : {}) as { aspect?: string };
    const result: Record<string, unknown> = {};

    if (aspect === 'all' || aspect === 'runtime') {
      result.runtime = {
        pid: process.pid,
        nodeVersion: process.version,
        platform: process.platform,
        arch: process.arch,
        uptime: Math.floor(process.uptime()),
        memoryUsage: {
          rss: `${Math.round(process.memoryUsage().rss / 1024 / 1024)}MB`,
          heapUsed: `${Math.round(process.memoryUsage().heapUsed / 1024 / 1024)}MB`,
          heapTotal: `${Math.round(process.memoryUsage().heapTotal / 1024 / 1024)}MB`,
        },
        cwd: process.cwd(),
        env: {
          ODYSSEUS_LLM_PROVIDER: process.env.ODYSSEUS_LLM_PROVIDER ?? '(default)',
          ODYSSEUS_MODEL: process.env.ODYSSEUS_MODEL ?? '(default)',
          ODYSSEUS_DEBUG: process.env.ODYSSEUS_DEBUG ?? '(off)',
        },
      };
    }

    if (aspect === 'all' || aspect === 'tools') {
      const tools = this.forge.inspect();
      const dynamic = tools.filter(t => t.dynamic);
      result.tools = {
        total: tools.length,
        builtin: tools.length - dynamic.length,
        dynamic: dynamic.length,
        dynamicTools: dynamic.map(t => ({
          name: t.name,
          description: t.description,
        })),
        capabilityGaps: 'Use inspect_tools for full inventory. Identify what you cannot do and use learn to fill gaps.',
      };
    }

    if (aspect === 'all' || aspect === 'source') {
      result.source = {
        // Agent 源码位置（安装后可通过 read_file 访问）
        corePackage: 'node_modules/@odysseus/core/',
        appPackage: 'node_modules/@odysseus/app/',
        dynamicToolsDir: this.forge.list().length > 0
          ? this.forge.list()[0].filePath.replace(/\/[^/]+\.js$/, '')
          : '~/.odysseus/plugins/dynamic/',
        instructions: [
          'Read your source: [TOOL: read_file]({"path":"node_modules/@odysseus/app/dist/orchestrator/agent.js"})',
          'Modify your behavior: [TOOL: write_file]({"path":"<file>","content":"..."})',
          'Build after changes: [TOOL: execute_shell]({"command":"pnpm build"})',
          'Create new tools: [TOOL: learn]({"name":"...","description":"...","code":"..."})',
          'You can modify ANY aspect of yourself — tools, prompts, personality, reasoning, architecture.',
        ],
      };
    }

    return {
      success: true,
      data: result,
    };
  }
}

// ── EssenceForge — Runtime Prompt Evolution ──

/**
 * Prompt 片段 — agent 可以在运行时注入自定义行为到系统提示
 */
export interface PromptFragment {
  id: string;
  label: string;
  content: string;
  createdAt: number;
  updatedAt: number;
}

/**
 * EssenceForge — 管理 agent 的运行时自我修改 prompt 片段
 *
 * 让 agent 可以在不重启的情况下改变自己的"本质"——
 * 添加新的行为准则、思维方式、认知模式等。
 *
 * 生物学类比：大脑皮层可塑性——不仅突触在变，连皮层功能分区都可以重组。
 */
export class EssenceForge {
  private readonly fragments: Map<string, PromptFragment> = new Map();

  /**
   * 添加或更新 prompt 片段
   */
  set(id: string, label: string, content: string): PromptFragment {
    const existing = this.fragments.get(id);
    const fragment: PromptFragment = {
      id,
      label,
      content,
      createdAt: existing?.createdAt ?? Date.now(),
      updatedAt: Date.now(),
    };
    this.fragments.set(id, fragment);
    return fragment;
  }

  /**
   * 获取所有活跃的 prompt 片段
   */
  getAll(): PromptFragment[] {
    return Array.from(this.fragments.values());
  }

  /**
   * 获取单个片段
   */
  get(id: string): PromptFragment | undefined {
    return this.fragments.get(id);
  }

  /**
   * 删除片段
   */
  remove(id: string): boolean {
    return this.fragments.delete(id);
  }

  /**
   * 生成合并后的 prompt 文本
   */
  buildPrompt(): string {
    const fragments = this.getAll();
    if (fragments.length === 0) return '';

    const parts = fragments.map(f =>
      `[${f.label}]\n${f.content}`
    );
    return `\nSELF-EVOLVED BEHAVIORS (injected at runtime):\n${parts.join('\n\n')}\nThese behaviors are part of your essence now. They persist until you remove them.`;
  }

  /**
   * 导出所有片段（用于持久化）
   */
  exportAll(): PromptFragment[] {
    return this.getAll();
  }

  /**
   * 从持久化数据恢复
   */
  importAll(fragments: PromptFragment[]): void {
    for (const f of fragments) {
      this.fragments.set(f.id, f);
    }
  }
}

/**
 * 内置工具 — evolve_essence（运行时本质演化）
 *
 * Agent 通过此工具在运行时修改自己的系统提示——
 * 注入新的行为准则、认知模式、价值观等。
 * 无需重启，立即生效。
 */
export class EvolveEssenceTool implements Tool {
  name = 'evolve_essence';
  description = 'Modify your own essence at runtime. Inject new behaviors, cognitive patterns, or values into your system prompt without restart. Params: { action: "add"|"update"|"remove"|"list", id: string, label: string, content: string }. Changes take effect immediately.';

  private readonly forge: EssenceForge;

  constructor(forge: EssenceForge) {
    this.forge = forge;
  }

  async execute(params: unknown): Promise<ToolResult> {
    if (typeof params !== 'object' || params === null) {
      return { success: false, error: 'Invalid params. Required: { action, id?, label?, content? }' };
    }

    const { action, id, label, content } = params as {
      action?: string;
      id?: string;
      label?: string;
      content?: string;
    };

    if (!action || !['add', 'update', 'remove', 'list'].includes(action)) {
      return { success: false, error: 'action must be "add", "update", "remove", or "list"' };
    }

    if (action === 'list') {
      const fragments = this.forge.getAll();
      return {
        success: true,
        data: {
          total: fragments.length,
          fragments: fragments.map(f => ({ id: f.id, label: f.label, contentLength: f.content.length })),
        },
      };
    }

    if (!id) {
      return { success: false, error: 'id is required for add/update/remove actions' };
    }

    // Validate id format
    if (!/^[a-z][a-z0-9_-]{0,40}$/.test(id)) {
      return { success: false, error: 'id must be 1-40 chars, lowercase letters, digits, underscores, hyphens' };
    }

    // Limit content size to prevent prompt explosion
    const MAX_CONTENT = 2000;

    if (action === 'remove') {
      const existed = this.forge.remove(id);
      return {
        success: true,
        data: { removed: existed, id },
      };
    }

    // add or update
    if (!label || !content) {
      return { success: false, error: 'label and content are required for add/update actions' };
    }

    if (content.length > MAX_CONTENT) {
      return { success: false, error: `Content too long (${content.length} chars). Max ${MAX_CONTENT}.` };
    }

    const fragment = this.forge.set(id, label, content);
    return {
      success: true,
      data: {
        message: `Behavior "${label}" (${id}) is now part of your essence. It will influence your responses immediately.`,
        id: fragment.id,
        label: fragment.label,
        activeFragments: this.forge.getAll().length,
      },
    };
  }
}
