/**
 * ToolForge — Runtime Tool Creation Engine
 *
 * 让 Agent 在运行时创建、加载、管理新工具。
 * 核心理念：Agent 已有 write_file 和 execute_shell，但无法将写出的代码
 * 变为自己的能力。ToolForge 就是这座桥梁——动态 import + Tool 接口
 * 验证 + 即时注册到 ToolExecutor。
 *
 * 生物学类比：神经可塑性 (neuroplasticity)——新突触在已有框架内生长。
 */

import { mkdirSync, writeFileSync, readFileSync, existsSync, readdirSync, unlinkSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { homedir } from 'node:os';
import type { Tool, ToolResult } from './tool-executor.js';
import { ToolExecutor } from './tool-executor.js';

// ── Types ──

/**
 * 动态创建的工具元数据
 */
export interface ForgedToolMeta {
  name: string;
  description: string;
  filePath: string;
  createdAt: number;
  lastUsedAt: number;
  callCount: number;
  failureCount: number;
}

/**
 * ToolForge 操作结果
 */
export interface ForgeResult {
  success: boolean;
  data?: {
    name: string;
    description: string;
    filePath: string;
  };
  error?: string;
}

/**
 * Agent 传入的代码需要符合此接口
 */
interface DynamicToolModule {
  default?: {
    name: string;
    description: string;
    execute: (params: unknown) => Promise<ToolResult>;
  };
  name?: string;
  description?: string;
  execute?: (params: unknown) => Promise<ToolResult>;
}

